"""Pack assets/voice/*.wav into src/voice_data.cpp, in tools/voice_phrases.tsv order.

python tools/pack_voice.py           rewrite src/voice_data.cpp
python tools/pack_voice.py --check   verify every clip and that the generated source is current
"""
from pathlib import Path
import re, struct, sys

root = Path(__file__).resolve().parents[1]
MANIFEST = root / 'tools' / 'voice_phrases.tsv'
CLIPS = root / 'assets' / 'voice'
SOURCE = root / 'src' / 'voice_data.cpp'
RATE = 16000              # Mono 8-bit unsigned PCM: about 16 KB of flash per second of speech.
HEADER = 44               # Canonical RIFF header: fmt chunk, then data, nothing else.
CAPTION_CHARS = 47        # One line of the home-screen speech strip (BubbleChars).
MAX_SECONDS = 1.6         # Synthesized clips aim for 1.5 s; a longer phrase should be reworded.
LEGACY_MAX_SECONDS = 3.0  # The three older recordings are longer sentences.
MAX_TOTAL = 900_000       # Flash budget for every clip together.


def manifest():
    """Rows of tools/voice_phrases.tsv as dicts: id, spoken, caption, legacy, heard."""
    rows, seen = [], set()
    for number, line in enumerate(MANIFEST.read_text(encoding='ascii').splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        cells = line.split('\t')
        where = f'{MANIFEST.name}:{number}'
        assert len(cells) in (4, 5), f'{where}: expected id, spoken, caption, source[, heard as]'
        clip, spoken, caption, source = cells[:4]
        heard = cells[4].split('|') if len(cells) == 5 else []
        assert re.fullmatch(r'[a-z][a-z0-9_]*', clip), f'{where}: bad id {clip!r}'
        assert clip not in seen, f'{where}: duplicate id {clip}'
        assert spoken.strip() == spoken and spoken, f'{where}: empty or padded spoken text'
        assert caption and len(caption) <= CAPTION_CHARS, f'{where}: caption must be 1-{CAPTION_CHARS} characters'
        assert all(32 <= ord(c) < 127 for c in caption) and '"' not in caption and '\\' not in caption, \
            f'{where}: caption must be plain ASCII without quotes or backslashes'
        assert source in ('tts', 'legacy'), f'{where}: unknown source {source!r}'
        assert all(h.strip() for h in heard), f'{where}: empty "heard as" spelling'
        seen.add(clip)
        rows.append({'id': clip, 'spoken': spoken, 'caption': caption, 'legacy': source == 'legacy',
                     'heard': heard})
    assert rows, 'manifest is empty'
    return rows


def wav_header(samples):
    return struct.pack('<4sI4s4sIHHIIHH4sI', b'RIFF', 36 + samples, b'WAVE', b'fmt ', 16, 1, 1, RATE, RATE, 1, 8,
                       b'data', samples)


def read_clip(row):
    """Bytes of one clip, after checking the exact format the firmware and the budget expect."""
    path = CLIPS / f"{row['id']}.wav"
    assert path.is_file(), f'{path.relative_to(root)} is missing: run tools/generate_voice.py'
    data = path.read_bytes()
    samples = len(data) - HEADER
    assert samples > 0 and data[:HEADER] == wav_header(samples), \
        f'{path.name}: must be mono {RATE} Hz 8-bit unsigned PCM with a canonical {HEADER}-byte header'
    limit = LEGACY_MAX_SECONDS if row['legacy'] else MAX_SECONDS
    assert samples <= limit * RATE, f'{path.name}: {samples / RATE:.2f} s is over the {limit} s cap'
    return data


def render(rows, clips):
    out = ['// Generated by tools/pack_voice.py from assets/voice/*.wav. Do not edit.',
           '#include "voice.h"', 'namespace dash {', 'namespace {']
    for row, data in zip(rows, clips):
        out.append(f"const uint8_t clip_{row['id']}[] = {{")
        out += [','.join(map(str, data[at:at + 32])) + ',' for at in range(0, len(data), 32)]
        out.append('};')
    out.append('} // namespace')
    out.append('extern const ClipData VoiceClips[ClipCount] = {')
    out += [f"    {{clip_{row['id']}, sizeof(clip_{row['id']})}}," for row in rows]
    out += ['};', '} // namespace dash', '']
    return '\n'.join(out)


def build():
    rows = manifest()
    clips = [read_clip(row) for row in rows]
    total = sum(map(len, clips))
    assert total <= MAX_TOTAL, f'clips total {total} bytes, over the {MAX_TOTAL} byte budget'
    extra = sorted(p.name for p in CLIPS.glob('*') if p.stem not in {r['id'] for r in rows} or p.suffix != '.wav')
    assert not extra, f'assets/voice has files that are not in the manifest: {extra}'
    return rows, clips, total


if __name__ == '__main__':
    rows, clips, total = build()
    text = render(rows, clips)
    if '--check' in sys.argv:
        assert SOURCE.is_file() and SOURCE.read_text(encoding='ascii') == text, \
            'src/voice_data.cpp is out of date: run python tools/pack_voice.py'
        print(f'Voice clips passed ({len(rows)} clips, {total} bytes, {sum(len(c) - HEADER for c in clips) / RATE:.1f} s).')
    else:
        SOURCE.write_text(text, encoding='ascii', newline='\n')
        print(f'{SOURCE.relative_to(root)}: {len(rows)} clips, {total} bytes')
