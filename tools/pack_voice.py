from pathlib import Path
import array, io, sys, wave
out = ['// Generated by tools/generate_voice.ps1; original offline alert phrases.', '#pragma once', '#include <stdint.h>']
for name, filename in [('voicePig','pig.wav'),('voiceFuzz','fuzz.wav'),('voiceLove','love.wav')]:
    with wave.open(str(Path('.tools/audio')/filename), 'rb') as source:
        assert source.getsampwidth() == 2 and source.getcomptype() == 'NONE'
        params = source.getparams()
        samples = array.array('h', source.readframes(source.getnframes()))
    if sys.byteorder != 'little': samples.byteswap()
    peak = max(abs(v) for v in samples) or 1
    samples = array.array('h', (round(v * 29000 / peak) for v in samples))
    if sys.byteorder != 'little': samples.byteswap()
    buffer = io.BytesIO()
    with wave.open(buffer, 'wb') as output:
        output.setparams(params)
        output.writeframes(samples.tobytes())
    data = buffer.getvalue()
    assert data[:4] == b'RIFF' and data[8:12] == b'WAVE'
    out.append(f'static const uint8_t {name}[] = {{')
    for offset in range(0,len(data),24):
        out.append('  '+','.join(str(b) for b in data[offset:offset+24])+',')
    out.append('};')
Path('include/voice.h').write_text('\n'.join(out)+'\n')
