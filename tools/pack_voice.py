from pathlib import Path
out = ['// Generated by tools/generate_voice.ps1; original offline alert phrases.', '#pragma once', '#include <stdint.h>']
for name, filename in [('voicePig','pig.wav'),('voiceFuzz','fuzz.wav')]:
    data = (Path('.tools/audio')/filename).read_bytes()
    assert data[:4] == b'RIFF' and data[8:12] == b'WAVE'
    out.append(f'static const uint8_t {name}[] = {{')
    for offset in range(0,len(data),24):
        out.append('  '+','.join(str(b) for b in data[offset:offset+24])+',')
    out.append('};')
Path('include/voice.h').write_text('\n'.join(out)+'\n')
