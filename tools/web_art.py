"""Generate site/buddy_art.mjs from the buddy art in include/avatars.h.

The firmware header is the single source of truth for how the buddies look: body, face, every
piece of gear, the aura and the order they are layered in. This converts everything between its
web-art markers into JavaScript so Avatar Studio draws the same shapes. Run after editing the
art:  python tools/web_art.py   (--check only verifies)."""
from pathlib import Path
import re, sys
root = Path(__file__).resolve().parents[1]
source = (root / 'include' / 'avatars.h').read_text()
art = source.split('// <web-art-begin>', 1)[1].split('// <web-art-end>', 1)[0]

def names(parameters):
    return ', '.join(part.split()[-1].lstrip('&*') for part in parameters.split(','))

art = re.sub(r'template <class P>\s*void (\w+)\(P &p,\s*(.*?)\) \{',
             lambda m: f'export function {m.group(1)}(p, {names(m.group(2))}) {{', art, flags=re.S)
art = re.sub(r'inline (?:uint16_t|int|bool) (\w+)\((.*?)\) \{',
             lambda m: f'export function {m.group(1)}({names(m.group(2))}) {{', art, flags=re.S)
art = re.sub(r'static constexpr int (\w+)\[\]\[\d+\] = (\{.*?\});',
             lambda m: f'const {m.group(1)} = {m.group(2).replace("{", "[").replace("}", "]")};',
             art, flags=re.S)
art = re.sub(r'for \(auto &(\w+) : (\w+)\)', r'for (const \1 of \2)', art)
art = re.sub(r'for \(int (\w+) : \{([^}]*)\}\)', r'for (const \1 of [\2])', art)
art = re.sub(r'\b(?:uint16_t|int|bool) (?=\w+ =)', 'let ', art)
art = re.sub(r'\bint\(', 'Math.trunc(', art)
art = art.replace('art::', '')

# Sanity checks: refuse to write JavaScript that would not mean what the C++ means.
code = re.sub(r'//[^\n]*', '', art)
problems = []
leftover = re.findall(r'\b(?:uint16_t|uint8_t|int|bool|float|double|char|unsigned|auto|template|'
                      r'constexpr|static|inline|struct|sizeof|cos|sin|sqrtf?|l?roundf?|std)\b|::|->|\bg\.',
                      code)
if leftover:
    problems.append(f'C++ that has no conversion: {sorted(set(leftover))}')
pen = {'oval', 'box', 'tri', 'line2', 'bar'}
for pens in ('p', 'rim', 'edge'):
    unknown = set(re.findall(rf'\b{pens}\.(\w+)\(', code)) - pen
    if unknown:
        problems.append(f'pen calls the website cannot draw: {sorted(unknown)}')
defined = set(re.findall(r'export function (\w+)\(', code))
helpers = {'mix', 'dark', 'pale', 'dim'}  # Written by hand in the header below.
keywords = {'if', 'for', 'function', 'return', 'while', 'switch'}
called = set(re.findall(r'(?<![.\w])([A-Za-z_]\w*)\(', code)) - keywords
missing = called - defined - helpers
if missing:
    problems.append(f'calls to functions the website does not have: {sorted(missing)}')
for name in ('buddyArt', 'buddyBody', 'buddyDetails'):
    if name not in defined:
        problems.append(f'{name} is missing from the web-art section')
for opener, closer in ('{}', '()', '[]'):
    if code.count(opener) != code.count(closer):
        problems.append(f'unbalanced {opener}{closer}')
# Comments are gone by now, so any '/' left once the int(...) calls are removed is a division.
if '/' in re.sub(r'Math\.trunc\((?:[^()]|\([^()]*\))*\)', '', code):
    problems.append('a division outside int(...): C++ truncates it, JavaScript would not')
if problems:
    sys.exit('web_art.py cannot convert include/avatars.h:\n  ' + '\n  '.join(problems))

header = '''// GENERATED by tools/web_art.py from include/avatars.h. Do not edit; edit the header and rerun.
// Colours are RGB565 integers, exactly as on the device. A look is
// {base, custom, body, accent, eye, eyes, headwear, eyewear, neckwear, mark, back, held, aura}.
export const Ink = 0x1085, Paper = 0xff7a, Mint = 0x87b6, Peach = 0xfdaf, Lilac = 0xc5ff, Blush = 0xfbb2;
export const css = c => `rgb(${Math.round((c >> 11) * 255 / 31)},${Math.round(((c >> 5) & 63) * 255 / 63)},${Math.round((c & 31) * 255 / 31)})`;
export function mix(a, b, n, d) {
  const part = (shift, mask) => Math.trunc((((a >> shift) & mask) * (d - n) + ((b >> shift) & mask) * n) / d);
  return (part(11, 31) << 11) | (part(5, 63) << 5) | part(0, 31);
}
export const dark = c => ((c >> 11) & 31) * 2 + ((c >> 5) & 63) * 2 + (c & 31) < 46;
export const pale = c => ((c >> 11) & 31) * 2 + ((c >> 5) & 63) * 2 + (c & 31) > 180;
export const dim = c => ((c >> 11) & 31) * 2 + ((c >> 5) & 63) * 2 + (c & 31) < 110;
export function buddyTones(avatar, custom, customBody, customAccent) {
  const body = custom ? customBody : [Paper, Mint, Lilac, 0x0000, 0xfa64][avatar];
  const blush = custom ? customAccent : avatar === 3 ? 0xc5ff : avatar === 4 ? 0xff28 : Blush;
  const night = dark(body);
  const shade = night ? mix(body, 0xc5ff, 1, 6) : mix(body, Ink, 1, 5);
  return {
    body, blush, shade,
    line: night ? mix(body, 0xc5ff, 3, 5) : mix(body, Ink, 13, 20),
    light: mix(body, 0xffff, night ? 1 : 3, 5),
    trim: custom ? mix(body, Ink, 3, 10) : avatar === 1 ? 0x35d0 : avatar === 2 ? 0x8bdb : shade,
  };
}
// The canvas counterpart of art::Pen: grow > 0 draws every shape fatter in the outline colour.
export function makePen(g, grow, line) {
  const ink = c => css(grow ? line : c);
  return {
    oval(x, y, rx, ry, c) { g.fillStyle = ink(c); g.beginPath(); g.ellipse(x, y, rx + grow + .5, ry + grow + .5, 0, 0, Math.PI * 2); g.fill(); },
    box(x, y, w, h, r, c) { g.fillStyle = ink(c); g.beginPath(); g.roundRect(x - grow, y - grow, w + 2 * grow, h + 2 * grow, Math.max(0, Math.min(r + grow, (Math.min(w, h) + 2 * grow) / 2))); g.fill(); },
    tri(x0, y0, x1, y1, x2, y2, c) {
      const pts = [[x0, y0], [x1, y1], [x2, y2]];
      if (grow) {
        const mx = (x0 + x1 + x2) / 3, my = (y0 + y1 + y2) / 3;
        for (const pt of pts) { const dx = pt[0] - mx, dy = pt[1] - my, len = Math.hypot(dx, dy); if (len) { pt[0] += dx / len * grow * 2; pt[1] += dy / len * grow * 2; } }
      }
      g.fillStyle = ink(c); g.beginPath(); g.moveTo(...pts[0]); g.lineTo(...pts[1]); g.lineTo(...pts[2]); g.closePath(); g.fill();
    },
    line2(x0, y0, x1, y1, c, w = 2) {
      if (grow) return;
      g.strokeStyle = css(c); g.lineWidth = w; g.lineCap = 'round'; g.beginPath(); g.moveTo(x0, y0); g.lineTo(x1, y1); g.stroke();
    },
    bar(x0, y0, x1, y1, c, w) {
      g.strokeStyle = ink(c); g.lineWidth = w + 2 * grow; g.lineCap = 'round'; g.beginPath(); g.moveTo(x0, y0); g.lineTo(x1, y1); g.stroke();
    },
  };
}
'''
output = header + art.strip('\n') + '\n'
target = root / 'site' / 'buddy_art.mjs'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != output:
        sys.exit('site/buddy_art.mjs is out of date. Run: python tools/web_art.py')
    print('Web buddy art matches include/avatars.h.')
else:
    target.write_text(output)
    print(f'Wrote {target.relative_to(root)}')
